public class Ejercicio2Mod {
    public static void main(String[] args){
        int inicial = 0;
        System.out.println("Puntuación inicial: "+inicial);

        inicial = 5;
        System.out.println("Después de primera modificación: "+inicial);

        inicial = 10;
        System.out.println("Despues de segunda modificación: "+inicial);

        inicial = 15;
        System.out.println("Puntuación final: "+inicial);
    }
}
